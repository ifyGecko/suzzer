#!/usr/bin/env python3
"""
gen_patchlist_baremetal.py -- build an LCV3 patch list for a baremetal/RTOS
image, from an ELF's function entry points, and emit it as a C source file
(a byte array + length) to bake into a libcov freestanding core blob.

Standalone: depends only on a cross objdump. Not tied to any particular board
or firmware -- you pass the ELF, the module base address the records are
relative to, and the symbols (block entries) to instrument.

Usage:
  gen_patchlist_baremetal.py --objdump mips-linux-gnu-objdump --elf a.elf \
      --base 0x80100000 --module test --out-c patchlist.c SYM [SYM ...]

Each record: offset = symbol_addr - base, len = 4, orig = the 4 instruction
bytes in target (memory) order. Sites whose first instruction is a branch/
jump are skipped (never patch a branch or a delay-slot owner). Little-endian
on the wire per the LCV3 format, regardless of target endianness.
"""
import argparse, struct, subprocess, sys, re

def first_insn(objdump, elf, sym):
    # disassemble just the symbol and read its first instruction word
    out = subprocess.check_output([objdump, "-d", "--disassemble="+sym, elf],
                                  text=True, stderr=subprocess.DEVNULL)
    addr = None; word = None
    for line in out.splitlines():
        m = re.match(r'^\s*([0-9a-fA-F]+):\s+([0-9a-fA-F]{8})\s', line)
        if m:
            addr = int(m.group(1), 16); word = int(m.group(2), 16); break
    return addr, word

def is_branch(word):
    op = word >> 26
    if op in (0x02,0x03,0x04,0x05,0x06,0x07,0x01,0x14,0x15,0x16,0x17): return True
    if op == 0x00:                              # SPECIAL: jr/jalr
        fn = word & 0x3f
        if fn in (0x08,0x09): return True
    return False

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--objdump", default="mips-linux-gnu-objdump")
    ap.add_argument("--elf", required=True)
    ap.add_argument("--base", required=True)
    ap.add_argument("--module", default="module0")
    ap.add_argument("--out-c", required=True)
    ap.add_argument("syms", nargs="+")
    a = ap.parse_args()
    base = int(a.base, 0)

    recs = []
    for sym in a.syms:
        addr, word = first_insn(a.objdump, a.elf, sym)
        if addr is None:
            print(f"warn: {sym}: not found, skipped", file=sys.stderr); continue
        if is_branch(word):
            print(f"warn: {sym} @ {addr:#x}: first insn is a branch, skipped", file=sys.stderr); continue
        orig = struct.pack(">I", word)          # target is big-endian MIPS
        recs.append((addr - base, orig, sym, addr))

    name = a.module.encode() + b"\x00"
    header_size = 24
    rec_size = 14
    modules_offset = header_size + rec_size * len(recs)
    modules_size = len(name)
    blob = bytearray()
    blob += b"LCV3"
    blob += struct.pack("<I", 3)                # version
    blob += struct.pack("<I", len(recs))        # count
    blob += bytes([0, 0, 1, 0])                 # threading=ANY, flags, module_count=1, reserved
    blob += struct.pack("<I", modules_offset)
    blob += struct.pack("<I", modules_size)
    for off, orig, sym, addr in recs:
        blob += struct.pack("<Q", off) + bytes([4, 0]) + orig
    blob += name

    with open(a.out_c, "w") as f:
        f.write("/* generated by gen_patchlist_baremetal.py -- do not edit */\n")
        f.write("const unsigned char libcov_bm_patchlist[] = {\n")
        for i in range(0, len(blob), 12):
            f.write("    " + ",".join("0x%02x" % b for b in blob[i:i+12]) + ",\n")
        f.write("};\n")
        f.write("const unsigned long libcov_bm_patchlist_len = %d;\n" % len(blob))
    print(f"wrote {a.out_c}: {len(recs)} sites, {len(blob)} bytes LCV3", file=sys.stderr)
    for off, orig, sym, addr in recs:
        print(f"  site {sym} @ {addr:#x} off={off:#x} orig={orig.hex()}", file=sys.stderr)

if __name__ == "__main__":
    main()
